# Step 3: Compute Fundamental Matrix using A-matrix approach (8-point algorithm)
def compute_fundamental_matrix(points1, points2):
    n = len(points1)
    A = np.zeros((n, 9))  # A is an n×9 matrix where n is the number of correspondences.
    # to construct A matrix by taking corresponding points which are (x1,y1) & (x2,y2)
    for i in range(n):
        x1, y1 = points1[i]
        x2, y2 = points2[i]
        A[i] = [x1 * x2, x1 * y2, x1, y1 * x2, y1 * y2, y1, x2, y2, 1]

    # Solve for F using SVD
    U, S, Vt = np.linalg.svd(A)
    F = Vt[-1].reshape(3, 3)  # The last row of Vt (corresponding to the smallest singular value) gives the solution to A

    # Enforce rank-2 constraint
    U, S, Vt = np.linalg.svd(F)  # U, S, Vt: Components of the SVD of F & S: Singular values of F, which indicate its rank
    S[2] = 0  # Setting the smallest singular value (S[2]) to zero reduces the rank of F to 2 [s1, s2, s3] or we are setting the rank as 2 constraint by zeroing out the smallest singular value
    F = U @ np.diag(S) @ Vt  # Rebuild the fundamental matrix F using the modified singular values S. The reconstructed F now has rank 2.

    return F

