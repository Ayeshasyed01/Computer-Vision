def draw_epipolar_lines(image1, image2, points1, points2, F):
    """
    Draw epipolar lines on both images.
    Args:
        image1, image2: The input images (BGR format).
        points1, points2: Point correspondences.
        F: Fundamental matrix.
    Returns:
        Two images with epipolar lines drawn.
    """
    # Compute epipolar lines for points in image 2 (lines on image 1)
    lines1 = cv2.computeCorrespondEpilines(points2.reshape(-1, 1, 2), 2, F).reshape(-1, 3)
    # Compute epipolar lines for points in image 1 (lines on image 2)
    lines2 = cv2.computeCorrespondEpilines(points1.reshape(-1, 1, 2), 1, F).reshape(-1, 3)

    img1_color = image1.copy()
    img2_color = image2.copy()

    for r1, r2, pt1, pt2 in zip(lines1, lines2, points1, points2):
        # Random color for each pair
        color = tuple(np.random.randint(0, 255, 3).tolist())

        # Epipolar line on image 1
        x0, y0 = map(int, [0, -r1[2] / r1[1]])
        x1, y1 = map(int, [img1_color.shape[1], -(r1[2] + r1[0] * img1_color.shape[1]) / r1[1]])
        img1_color = cv2.line(img1_color, (x0, y0), (x1, y1), color, 1)
        img1_color = cv2.circle(img1_color, tuple(map(int, pt1)), 5, color, -1)

        # Epipolar line on image 2
        x0, y0 = map(int, [0, -r2[2] / r2[1]])
        x1, y1 = map(int, [img2_color.shape[1], -(r2[2] + r2[0] * img2_color.shape[1]) / r2[1]])
        img2_color = cv2.line(img2_color, (x0, y0), (x1, y1), color, 1)
        img2_color = cv2.circle(img2_color, tuple(map(int, pt2)), 5, color, -1)

    return img1_color, img2_color

