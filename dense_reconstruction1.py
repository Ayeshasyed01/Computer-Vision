# Step 6: Compute Disparity Map
def compute_disparity(img1, img2, block_size=3, min_disp=0, num_disp=16*5):
    # Normalize images
    img1 = cv2.normalize(img1, None, alpha=0, beta=255, norm_type=cv2.NORM_MINMAX)
    img2 = cv2.normalize(img2, None, alpha=0, beta=255, norm_type=cv2.NORM_MINMAX)

    stereo = cv2.StereoSGBM_create(
        minDisparity=min_disp,
        numDisparities=num_disp,
        blockSize=block_size,
        P1=8 * 3 * block_size**2,
        P2=32 * 3 * block_size**2,
        disp12MaxDiff=1,
        uniquenessRatio=10,
        speckleWindowSize=100,
        speckleRange=32
    )
    disparity = stereo.compute(image1, image2).astype(np.float32) / 16.0
    return disparity

disparity = compute_disparity(image1, image2)

# Step 8: 3D Reconstruction
def reconstruct_3d(disparity, Q):
    # Q is the re-projection matrix, usually derived from stereo rectification
    points_3d = cv2.reprojectImageTo3D(disparity, Q)
    mask = disparity > disparity.min()
    points_3d = points_3d[mask]
    return points_3d

